#pragma once
#include <ntddk.h>

#define IO_GET_PROCESS_LIST CTL_CODE(FILE_DEVICE_UNKNOWN, 0x1724, METHOD_BUFFERED, FILE_SPECIAL_ACCESS)

#define IO_COPY_MEMORY CTL_CODE(FILE_DEVICE_UNKNOWN, 0x1725, METHOD_BUFFERED, FILE_SPECIAL_ACCESS)

#define IO_UNLOAD_DRIVER CTL_CODE(FILE_DEVICE_UNKNOWN, 0x1726, METHOD_BUFFERED, FILE_SPECIAL_ACCESS)

#define IO_GET_PROCESS_PEB CTL_CODE(FILE_DEVICE_UNKNOWN, 0x1727, METHOD_BUFFERED, FILE_SPECIAL_ACCESS)

#define IO_GET_PROCESS_MODULES CTL_CODE(FILE_DEVICE_UNKNOWN, 0x1728, METHOD_BUFFERED, FILE_SPECIAL_ACCESS)

typedef struct _KERNEL_PROCESS_LIST_OPERATION
{
	PVOID bufferAddress;
	INT32 bufferSize;
	INT32 processCount;
} KERNEL_PROCESS_LIST_OPERATION, *PKERNEL_PROCESS_LIST_OPERATION;

typedef struct _KERNEL_COPY_MEMORY_OPERATION
{
	INT32 targetProcessId;
	PVOID targetAddress;
	PVOID bufferAddress;
	INT32 bufferSize;
} KERNEL_COPY_MEMORY_OPERATION, *PKERNEL_COPY_MEMORY_OPERATION;

typedef struct _KERNEL_GET_PEB_OPERATION
{
	INT32 targetProcessId;
	PVOID pebAddress;
	NTSTATUS status;
} KERNEL_GET_PEB_OPERATION, *PKERNEL_GET_PEB_OPERATION;

typedef struct _KERNEL_MODULE_INFO
{
	PVOID baseAddress;
	ULONG sizeOfImage;
	BOOLEAN isWow64Process;
	WCHAR moduleName[256];
} KERNEL_MODULE_INFO, *PKERNEL_MODULE_INFO;

// FIXED: Separate input and output structures for cleaner buffer layout
typedef struct _KERNEL_GET_MODULES_INPUT
{
	INT32 targetProcessId;
	INT32 maxModules;
} KERNEL_GET_MODULES_INPUT, *PKERNEL_GET_MODULES_INPUT;

typedef struct _KERNEL_GET_MODULES_OUTPUT
{
	INT32 moduleCount;
	NTSTATUS status;
	KERNEL_MODULE_INFO modules[1]; // Variable length array
} KERNEL_GET_MODULES_OUTPUT, *PKERNEL_GET_MODULES_OUTPUT;